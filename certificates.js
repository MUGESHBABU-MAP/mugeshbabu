/* Certificates gallery. No dependencies.
   Reads images/certificates/certificates.json (generated by
   scripts/generate-certificates.mjs) and renders a lazy-loaded gallery with
   a keyboard-accessible full-screen viewer. All text is set with textContent
   and all elements are created with the DOM API, so file names are never
   interpreted as HTML. */
(() => {
  'use strict';
  const root = document.querySelector('[data-certs]');
  if (!root) return;

  const PREFIX = 'images/certificates/';
  const grid = root.querySelector('.cert-grid');
  const status = root.querySelector('.certs-status');
  const countEl = document.getElementById('certs-count');
  const pad = (n) => String(n).padStart(2, '0');
  const text = (el, value) => { el.textContent = value; return el; };
  const make = (tag, cls) => { const el = document.createElement(tag); if (cls) el.className = cls; return el; };

  /* ---------- manifest -> safe entries ---------- */
  const srcOf = (it) => {
    if (!it || typeof it.src !== 'string') return null;
    const s = it.src;
    if (!s.startsWith(PREFIX) || s.length === PREFIX.length) return null;
    if (s.includes('..') || s.includes('?') || s.includes('#') || /[\\\s<>"']/.test(s)) return null;
    const v = typeof it.v === 'string' && /^[a-z0-9]{4,16}$/i.test(it.v) ? '?v=' + it.v : '';
    return s + v;
  };
  const dim = (n) => (Number.isFinite(n) && n > 0 && n < 100000 ? Math.round(n) : 0);
  const oneLine = (v) => (typeof v === 'string' ? v.replace(/\s+/g, ' ').trim() : '');
  const altFor = (title) => (/^certificate\b/i.test(title) ? title : 'Certificate: ' + title);

  function toEntries(items) {
    const entries = [];
    const seenSrc = new Set();
    const seenTitle = new Map();
    items.forEach((it) => {
      const src = srcOf(it);
      if (!src || seenSrc.has(src)) return;
      seenSrc.add(src);
      let title = oneLine(it.title) || 'Certificate ' + pad(entries.length + 1);
      const key = title.toLowerCase();
      const n = (seenTitle.get(key) || 0) + 1;
      seenTitle.set(key, n);
      if (n > 1) title += ' (' + n + ')';
      entries.push({
        src, title, ok: true,
        width: dim(it.width), height: dim(it.height),
        issuer: oneLine(it.issuer), date: oneLine(it.date)
      });
    });
    return entries;
  }

  const visible = () => entries.filter((e) => e.ok);
  let entries = [];

  function showStatus(message) {
    grid.hidden = true;
    status.hidden = false;
    text(status, message);
    countEl.textContent = '';
    grid.removeAttribute('aria-busy');
  }

  function refresh() {
    const list = visible();
    countEl.textContent = list.length + (list.length === 1 ? ' certificate' : ' certificates');
    if (!list.length) showStatus('No certificates available yet.');
  }

  /* A thumbnail that cannot be loaded or decoded is dropped; the rest stay. */
  function drop(entry) {
    if (!entry.ok) return;
    entry.ok = false;
    entry.li.remove();
    refresh();
  }

  function render() {
    const frag = document.createDocumentFragment();
    entries.forEach((entry) => {
      const li = make('li', 'cert');
      const btn = make('button', 'cert-btn');
      btn.type = 'button';
      btn.setAttribute('aria-haspopup', 'dialog');
      btn.setAttribute('aria-label', 'View ' + entry.title);

      const plate = make('span', 'cert-plate');
      const img = make('img', 'cert-img');
      img.alt = entry.title + ', certificate preview';
      img.loading = 'lazy';
      img.decoding = 'async';
      if (entry.width && entry.height) { img.width = entry.width; img.height = entry.height; }
      img.addEventListener('load', () => {
        if (!img.naturalWidth) drop(entry); else plate.classList.add('is-loaded');
      });
      img.addEventListener('error', () => drop(entry));
      img.src = entry.src;
      plate.appendChild(img);

      const cap = make('span', 'cert-cap');
      const mark = make('span', 'cert-mark');
      mark.setAttribute('aria-hidden', 'true');
      cap.append(mark, text(make('span', 'cert-title'), entry.title));
      const meta = [entry.issuer, entry.date].filter(Boolean).join(' · ');
      if (meta) cap.appendChild(text(make('span', 'cert-meta'), meta));

      btn.append(plate, cap);
      li.appendChild(btn);
      frag.appendChild(li);
      Object.assign(entry, { li, btn });
      btn.addEventListener('click', () => openViewer(entry, btn));
    });
    grid.appendChild(frag);
    status.hidden = true;
    grid.hidden = false;
    refresh();
  }

  /* ---------- viewer ---------- */
  const dlg = document.getElementById('lb');
  const lbImg = document.getElementById('lb-img');
  const lbTitle = document.getElementById('lb-title');
  const lbCount = document.getElementById('lb-count');
  const lbErr = document.getElementById('lb-err');
  const lbLive = document.getElementById('lb-live');
  const lbMeta = document.getElementById('lb-meta');
  const lbPrev = document.getElementById('lb-prev');
  const lbNext = document.getElementById('lb-next');
  const lbClose = document.getElementById('lb-close');
  let current = null;
  let opener = null;

  function show(entry) {
    const list = visible();
    const i = list.indexOf(entry);
    if (i < 0) return;
    current = entry;
    text(lbTitle, entry.title);
    text(lbCount, pad(i + 1) + ' / ' + pad(list.length));
    text(lbMeta, [entry.issuer, entry.date].filter(Boolean).join(' · '));
    lbMeta.hidden = !lbMeta.textContent;
    lbPrev.disabled = lbNext.disabled = list.length < 2;
    lbErr.hidden = true;
    lbImg.classList.remove('is-ready');
    lbImg.alt = altFor(entry.title);
    lbImg.src = entry.src;
    text(lbLive, entry.title + ', ' + (i + 1) + ' of ' + list.length);
  }

  function step(delta) {
    const list = visible();
    if (list.length < 2 || !current) return;
    const i = list.indexOf(current);
    show(list[(i + delta + list.length) % list.length]);
  }

  function openViewer(entry, trigger) {
    if (typeof dlg.showModal !== 'function') { window.open(entry.src, '_blank', 'noopener'); return; }
    opener = trigger;
    document.documentElement.classList.add('lb-open');
    dlg.showModal();
    show(entry);
    lbClose.focus();
  }

  lbImg.addEventListener('load', () => lbImg.classList.add('is-ready'));
  lbImg.addEventListener('error', () => { lbImg.classList.remove('is-ready'); lbErr.hidden = false; });
  lbPrev.addEventListener('click', () => step(-1));
  lbNext.addEventListener('click', () => step(1));
  lbClose.addEventListener('click', () => dlg.close());

  dlg.addEventListener('keydown', (e) => {
    if (e.defaultPrevented || e.altKey || e.ctrlKey || e.metaKey) return;
    if (e.key === 'Tab') {                      // keep focus inside the viewer
      const stops = [lbClose, lbPrev, lbNext].filter((b) => !b.disabled);
      const first = stops[0], last = stops[stops.length - 1];
      const here = document.activeElement;
      if (!stops.includes(here) || (e.shiftKey && here === first) || (!e.shiftKey && here === last)) {
        e.preventDefault();
        (e.shiftKey && stops.includes(here) ? last : first).focus();
      }
      return;
    }
    if (e.key === 'ArrowRight') { e.preventDefault(); step(1); }
    else if (e.key === 'ArrowLeft') { e.preventDefault(); step(-1); }
    else if (e.key === 'Home') { e.preventDefault(); const l = visible(); if (l.length) show(l[0]); }
    else if (e.key === 'End') { e.preventDefault(); const l = visible(); if (l.length) show(l[l.length - 1]); }
  });

  /* click on the empty area around the image closes the viewer */
  dlg.addEventListener('click', (e) => {
    const t = e.target;
    if (t === dlg || (t.classList && (t.classList.contains('lb-in') || t.classList.contains('lb-stage') || t.classList.contains('lb-fig')))) dlg.close();
  });

  /* horizontal swipe on touch screens */
  let sx = 0, sy = 0;
  dlg.addEventListener('touchstart', (e) => { const t = e.changedTouches[0]; sx = t.clientX; sy = t.clientY; }, { passive: true });
  dlg.addEventListener('touchend', (e) => {
    const t = e.changedTouches[0];
    const dx = t.clientX - sx, dy = t.clientY - sy;
    if (Math.abs(dx) > 50 && Math.abs(dx) > Math.abs(dy) * 1.5) step(dx < 0 ? 1 : -1);
  }, { passive: true });

  dlg.addEventListener('close', () => {
    document.documentElement.classList.remove('lb-open');
    lbImg.removeAttribute('src');
    current = null;
    const target = opener && document.contains(opener) ? opener : root.querySelector('.cert-btn');
    if (target) target.focus({ preventScroll: true });
    opener = null;
  });

  /* ---------- boot ---------- */
  fetch(root.dataset.manifest, { cache: 'no-cache' })
    .then((res) => { if (!res.ok) throw new Error('manifest ' + res.status); return res.json(); })
    .then((data) => {
      entries = toEntries(Array.isArray(data && data.items) ? data.items : []);
      if (!entries.length) { showStatus('No certificates available yet.'); return; }
      grid.setAttribute('aria-busy', 'true');
      render();
      grid.removeAttribute('aria-busy');
    })
    .catch(() => showStatus('The certificates could not be loaded right now.'));
})();
